<template>
  <div>
    <!-- Пример 1: Вывод свойств объекта -->
    <div>
      <h3>Пример 1: Вывод свойств объекта</h3>
      <p>Свойство a: {{ obj1.a }}</p>
      <p>Свойство b: {{ obj1.b }}</p>
      <p>Свойство c: {{ obj1.c }}</p>
      
      <h4>Альтернативный способ:</h4>
      <p>Свойство a: {{ obj1['a'] }}</p>
      <p>Свойство b: {{ obj1['b'] }}</p>
      <p>Свойство c: {{ obj1['c'] }}</p>
    </div>

    <!-- Пример 2: Сумма элементов объекта -->
    <div>
      <h3>Пример 2: Сумма элементов объекта</h3>
