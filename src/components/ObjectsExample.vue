  name: 'ObjectsExample',
  data() {
    return {
      // Объект для примера 1
      obj1: {a: 1, b: 2, c: 3},
      
      // Объект для примера 2
      obj2: {x: 1, y: 2, z: 3}
    }
  }
}
</script> 